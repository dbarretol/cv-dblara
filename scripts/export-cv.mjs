// Exports the public part of the master CV (YAML) to src/data/cv.json and downloads its images.
//
// Usage:
//   npm run export-cv -- "<path to master_cv.yaml>"
//   (or set CV_MASTER_PATH)
//
// Only allow-listed fields are exported. Anything else in the YAML (phone, private notes, comments)
// never reaches the repository. The script fails if the phone number shows up in the output.
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, extname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse } from 'yaml';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT_JSON = join(ROOT, 'src/data/cv.json');
const OUT_IMAGES = join(ROOT, 'src/assets/cv');

const source = process.argv[2] ?? process.env.CV_MASTER_PATH;
if (!source) {
	console.error('Missing path to master_cv.yaml (argument or CV_MASTER_PATH).');
	process.exit(1);
}

const master = parse(readFileSync(source, 'utf8'));

/** Keeps only the listed keys, renaming snake_case to camelCase and dropping empty values. */
function pick(item, keys) {
	const out = {};
	for (const key of keys) {
		let value = item?.[key];
		if (value === undefined || value === null || value === '' || (Array.isArray(value) && value.length === 0)) continue;
		if (typeof value === 'number' && /date|year/.test(key)) value = String(value);
		if (typeof value === 'string') value = value.replace(/\s+/g, ' ').trim();
		out[key.replace(/_([a-z])/g, (_, c) => c.toUpperCase())] = value;
	}
	return out;
}

const images = new Map(); // url -> local file name
function image(url) {
	if (!url) return undefined;
	if (!images.has(url)) {
		const ext = extname(new URL(url).pathname).toLowerCase() || '.png';
		const base = new URL(url).pathname.split('/').pop().replace(/\.[^.]+$/, '').replace(/[^A-Za-z0-9_-]/g, '');
		const hash = createHash('sha256').update(url).digest('hex').slice(0, 6);
		images.set(url, `${base.slice(0, 40)}-${hash}${ext}`);
	}
	return images.get(url);
}
const withImage = (item, obj) => {
	const file = image(item.image_url);
	return file ? { ...obj, image: file } : obj;
};

const p = master.profile;
const cv = {
	generated: {
		note: 'Generated by scripts/export-cv.mjs from master_cv.yaml. Do not edit by hand.',
		sourceVersion: String(master.meta?.version ?? ''),
		lastUpdated: String(master.meta?.last_updated ?? ''),
	},
	profile: {
		name: p.name,
		email: p.contact?.email,
		location: p.contact?.location,
		linkedin: p.contact?.linkedin,
		github: p.contact?.github,
		summary: String(p.summary ?? '').replace(/\s+/g, ' ').trim(),
	},
	experience: master.experience.map((i) =>
		pick(i, ['id', 'title', 'org', 'location', 'start_date', 'end_date', 'summary', 'bullets', 'tags']),
	),
	aiTraining: master.ai_training.map((i) =>
		withImage(i, pick(i, ['id', 'title', 'program', 'org', 'location', 'start_date', 'end_date', 'status', 'summary', 'distinction', 'tags'])),
	),
	projects: master.projects.map((i) =>
		pick(i, ['id', 'title', 'context', 'start_date', 'end_date', 'status', 'summary', 'bullets', 'tags']),
	),
	education: master.education.map((i) =>
		withImage(i, pick(i, ['id', 'degree', 'specialization', 'org', 'location', 'start_date', 'end_date', 'distinction', 'thesis', 'thesis_url'])),
	),
	certifications: master.certifications.map((i) =>
		withImage(i, pick(i, ['id', 'title', 'issuer', 'date', 'expiry_date', 'credential_url'])),
	),
	skills: {
		technical: Object.entries(master.skills.technical).map(([group, list]) => ({
			group,
			items: list.map((s) => pick(s, ['name', 'level'])),
		})),
		soft: master.skills.soft_skills,
	},
	languages: master.languages.map((l) => pick(l, ['language', 'level', 'cefr'])),
	publications: master.publications.map((i) =>
		pick(i, ['id', 'type', 'title', 'authors', 'venue', 'institution', 'year', 'volume', 'pages', 'article_number', 'doi', 'url']),
	),
	awards: master.awards.map((i) => pick(i, ['id', 'title', 'org', 'date', 'end_date', 'summary'])),
	activities: master.activities.map((i) =>
		pick(i, ['id', 'title', 'org', 'orgs', 'program', 'event', 'start_date', 'end_date', 'date', 'bullets', 'tags']),
	),
	courses: master.courses.map((i) => pick(i, ['id', 'title', 'org', 'year', 'start_date', 'end_date'])),
};

const json = JSON.stringify(cv, null, '\t') + '\n';

// Safety net: the phone number must never be exported.
// Matches the last 9 digits with any spaces, dots or dashes between them.
const digits = String(p.contact?.phone ?? '').replace(/\D/g, '').slice(-9);
if (digits.length >= 6 && new RegExp(digits.split('').join('[\\s.\\-]*')).test(json)) {
	console.error('Aborting: the phone number appears in the exported data.');
	process.exit(1);
}

mkdirSync(dirname(OUT_JSON), { recursive: true });
writeFileSync(OUT_JSON, json);
console.log(`Wrote ${OUT_JSON}`);

mkdirSync(OUT_IMAGES, { recursive: true });
for (const [url, file] of images) {
	const target = join(OUT_IMAGES, file);
	if (existsSync(target)) continue;
	const res = await fetch(url, { headers: { 'User-Agent': 'cv-dblara-export/1.0 (+https://github.com/dbarretol/cv-dblara)' } });
	if (!res.ok) throw new Error(`Could not download ${url}: ${res.status}`);
	writeFileSync(target, Buffer.from(await res.arrayBuffer()));
	console.log(`Downloaded ${file}`);
}
